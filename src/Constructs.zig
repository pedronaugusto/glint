fn table(comptime Tag: type, comptime entries: []const Entry) std.EnumArray(Tag, ?Row) {
    @setEvalBranchQuota(100_000);
    var rows: std.EnumArray(Tag, ?Row) = .initFill(null);
    for (entries) |entry| if (std.meta.stringToEnum(Tag, entry[0])) |tag| rows.set(tag, entry[1]);
    return rows;
}

const zir_rows = table(Zir.Inst.Tag, &zir);
const extended_rows = table(Zir.Inst.Extended, &extended);
const ast_rows = table(Ast.Node.Tag, &ast);

/// A ZIR instruction's row; null for a tag this table does not place yet.
pub fn ofInstruction(tag: Zir.Inst.Tag) ?Row {
    return zir_rows.get(tag);
}

/// An extended ZIR instruction's row; null for one this table does not place yet.
pub fn ofExtended(opcode: Zir.Inst.Extended) ?Row {
    return extended_rows.get(opcode);
}

/// An Ast node's row; null for a form this table does not place yet.
pub fn ofNode(tag: Ast.Node.Tag) ?Row {
    return ast_rows.get(tag);
}

/// Each tag of `Tag` that `entries` places in no row, and each entry naming a tag `Tag` lacks,
/// a line to `w`.
fn complete(comptime Tag: type, comptime entries: []const Entry, kind: []const u8, w: *std.Io.Writer) std.Io.Writer.Error!void {
    for (std.meta.tags(Tag)) |tag| {
        for (entries) |entry| {
            if (std.mem.eql(u8, entry[0], @tagName(tag))) break;
        } else try w.print("{s} {s} is in no row: place it in Constructs.zig\n", .{ kind, @tagName(tag) });
    }
    for (entries) |entry| if (std.meta.stringToEnum(Tag, entry[0]) == null) {
        try w.print("{s} {s} is no tag of this Zig: take it out of Constructs.zig\n", .{ kind, entry[0] });
    };
}

